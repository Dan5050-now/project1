//
//  . 빈칸   # 땅      B 벽돌(부서짐)   ? 아이템 블록   1 숨겨진 1UP 블록
//  = 통과 발판(아래에서 뚫고 올라감)   ^ 바닥 가시   v 천장 가시
//  L/l 용암(표면/속)   Q/q 모래늪(표면/속)   X 무너지는 블록
//  M/m 좌우 이동 발판(m은 반대 위상)   N/n 상하 이동 발판(n은 위에서 시작)
//  C 코인  H 하트  P 시작 위치  K 체크포인트  S 표지판
//  A 보스 구역 시작  Z 보스 등장 위치
//  적: e 걷는 적  h 점프하는 적  y 나는 적  t 포탑  c 추적자  o 가시 적  d 낙하물
// ─────────────────────────────────────────────────────────────

function joinChunks(chunks) {
  const rows = new Array(ROWS).fill('');
  for (const ch of chunks) {
    if (ch.length !== ROWS) throw new Error('청크 줄 수 오류: ' + ch.length);
    const w = Math.max(...ch.map((r) => r.length));
    for (let r = 0; r < ROWS; r++) rows[r] += ch[r].padEnd(w, '.');
  }
  return rows;
}
function arena(top, rows) {
  // 보스 구역 공통 틀: 27칸, 오른쪽 벽
  const out = [];
  for (let r = 0; r < ROWS; r++) {
    if (rows && rows[r] != null) { out.push(rows[r]); continue; }
    if (r >= 11) out.push('#'.repeat(27));
    else if (top && r < top) out.push('#'.repeat(27));
    else out.push('.'.repeat(26) + '#');
  }
  return out;
}

